#include <stdio.h>

int main() {
  int num1 = 10;
  int num2 = 5;

  int soma = num1 + num2;
  int subtracao = num1 - num2;
  int multiplicacao = num1 * num2;
  int divisao = num1 / num2;

  printf("Soma: %d \n", soma);
  printf("Subtracao: %d \n", subtracao);
  printf("Multiplicacao: %d \n", multiplicacao);
  printf("Divisao: %d \n", divisao);

  return 0;
}